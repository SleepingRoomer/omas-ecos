export const sddLabel = (n) => (SDD[n - 1] ? `${n}. ${SDD[n - 1]}` : '');
export const sddFamily = (n) => SDD_FAMILIES.find((f) => n >= f.from && n <= f.to) || null;

const norm = (s) => String(s || '').toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '').replace(/[^a-z0-9]+/g, ' ').trim();
const NORM = SDD.map(norm);

// Les SDD d'une station, d'après le champ libre de l'éditeur : « 161. Douleur thoracique », « 161, 162 », ou un libellé seul
export function sddNumbers(text) {
  const t = String(text || '');
  const nums = [...t.matchAll(/(?:^|[^\d])(\d{1,3})(?=[^\d]|$)/g)].map((m) => Number(m[1])).filter((n) => n >= 1 && n <= 356);
  if (nums.length) return [...new Set(nums)];
  const n = norm(t);
  if (n.length < 4) return [];
  const exact = NORM.indexOf(n);
  if (exact >= 0) return [exact + 1];
  return NORM.map((l, i) => (l.length >= 6 && n.includes(l) ? i + 1 : 0)).filter(Boolean).slice(0, 3);
}
